// The application must display the installed APK version, never a stale footer label
// or the latest release advertised on GitHub.
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const file=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=file('app/src/main/assets/index.html');
const script=html.split('<script>')[1].split('</script>')[0];
new vm.Script(script);
const main=file('app/src/main/java/kr/co/firsthyundai/app/MainActivity.java');
const lock=file('app/src/main/java/kr/co/firsthyundai/app/LockActivity.java');
const native=file('app/src/main/java/kr/co/firsthyundai/app/AppVersion.java');
const gradle=file('app/build.gradle');
const workflow=file('.github/workflows/build-apk.yml');
const footer=html.match(/<footer[^>]*>[\s\S]*?<\/footer>/)?.[0]||'';
assert(footer,'Application footer must exist');
assert(!/\bv\d+\.\d+/.test(footer),'Footer must NEVER contain a static version literal');
assert(!/퍼스트현대 v1\.10/.test(html),'Stale v1.10 must be absent');
assert(html.includes('id="installedAppVersion"'),'Installed version should be visible to all family users');
assert(html.includes('id="securityAppVersion"'),'Version must appear in administrator security panel separately');
assert(/@JavascriptInterface public String getInstalledAppVersion\(\)/.test(main));
assert(/@JavascriptInterface public int getInstalledAppBuildNumber\(\)/.test(main));
assert(native.includes('getPackageManager().getPackageInfo(context.getPackageName(), 0)'),'Read actual PackageManager information');
assert(native.includes('info.versionName'),'Use PackageInfo versionName, not hardcoded text');
assert(native.includes('info.versionCode'),'Use real package versionCode');
assert(lock.includes('AppVersion.name(this)'),'Lock screen version comes from the installed package');
const props={};
const elem=id=>(props[id]||(props[id]={textContent:'*'}));
let bridge={getInstalledAppVersion:()=> '1.19.5',getInstalledAppBuildNumber:()=>37};
const ctx=vm.createContext({window:{FirstHyundaiNative:bridge},$:elem});
const begin=script.indexOf('function installedAppVersionLabel(');
const end=script.indexOf('function prettyTime(',begin);
assert(begin>=0&&end>begin);
vm.runInContext(script.slice(begin,end),ctx);
const label=()=>vm.runInContext('installedAppVersionLabel(window.FirstHyundaiNative)',ctx);
assert.strictEqual(label(),'설치된 앱 v1.19.5 · 빌드 37');
vm.runInContext('renderInstalledAppVersion()',ctx);
assert.strictEqual(props.installedAppVersion.textContent,'설치된 앱 v1.19.5 · 빌드 37');
assert.strictEqual(props.securityAppVersion.textContent,props.installedAppVersion.textContent);
bridge={getInstalledAppVersion:()=> '1.19.2',getInstalledAppBuildNumber:()=>34};
ctx.window.FirstHyundaiNative=bridge;
assert.strictEqual(label(),'설치된 앱 v1.19.2 · 빌드 34','Must show the old version on phones that have NOT updated');
ctx.window.FirstHyundaiNative={getInstalledAppVersion:()=>'<script>',getInstalledAppBuildNumber:()=>37};
assert(!label().includes('<script>'),'Unexpected native version must be rejected');
ctx.window.FirstHyundaiNative=undefined;
assert(!/\bv1\.\d+/.test(label()),'Offline HTML preview must not invent a version');
ctx.window.FirstHyundaiNative={getInstalledAppVersion(){throw new Error('missing')},getInstalledAppBuildNumber:()=>34};
assert(!/\bv1\.\d+/.test(label()),'Bridge error must not be replaced with fake version');
const buildName=gradle.match(/versionName '([^']+)'/);
const buildCode=gradle.match(/versionCode (\d+)/);
assert(buildName&&buildCode);
const releaseTag='v'+buildName[1];
assert(workflow.includes('gh release create '+releaseTag+' '),'Release version must match APK versionName');
assert(workflow.includes('FirstHyundai-'+releaseTag+'.apk'),'APK filename must match installed version');
console.log('App version label regression passed: native installed metadata, footer, security, lock screen, offline fallback, release consistency.');
