import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const context={window:{}};
vm.runInNewContext(fs.readFileSync('app/src/main/assets/office-phones.js','utf8'),context);
const {format,normalize,linkify}=context.window.FirstHyundaiPhones;
assert.equal(normalize('예약 345ㅡ6789'), '예약 032-345-6789');
assert.equal(normalize('예약 345-6789'), '예약 032-345-6789');
assert.equal(normalize('전화 1234—5678'), '전화 032-1234-5678');
assert.equal(normalize('전화번호: 3456789'), '전화번호: 032-345-6789');
assert.equal(normalize('전화 12345678'), '전화 032-1234-5678');
assert.equal(normalize('방문 1502/601 내일 11시30~40 예약. 전화 345ㅡ6789'),
 '방문 1502/601 내일 11시30~40 예약. 전화 032-345-6789');
assert.equal(normalize('010ㅡ1234ㅡ5678'), '010-1234-5678');
assert.equal(normalize('02-345-6789'), '02-345-6789');
assert.equal(normalize('032ㅡ345ㅡ6789'), '032-345-6789');
assert.equal(normalize('070ㅡ1234ㅡ5678'), '070-1234-5678');
assert.equal(normalize('1588ㅡ1234'), '1588-1234');
assert.equal(normalize('1544-1234'), '1544-1234');
assert.equal(normalize('가격 12345678 1502동 601호'), '가격 12345678 1502동 601호');
assert.equal(normalize(normalize('345ㅡ6789')), '032-345-6789');
assert.equal(format('345ㅡ6789'), '032-345-6789');
const escaped=v=>String(v).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const html=linkify('예약 345ㅡ6789 <script>',escaped);
assert(html.includes('href="tel:0323456789"'));
assert(html.includes('032-345-6789'));
assert(html.includes('&lt;script&gt;'));
assert(!html.includes('<script>'));
const index=fs.readFileSync('app/src/main/assets/index.html','utf8');
assert(index.indexOf('office-phones.js')<index.indexOf('office-board.js'));
const board=fs.readFileSync('app/src/main/assets/office-board.js','utf8');
assert(board.includes('FirstHyundaiPhones?.normalize?.(value)'));
const native=fs.readFileSync('app/src/main/java/kr/co/firsthyundai/app/OfficeMemoNotifications.java','utf8');
assert(native.includes('firsthyundai_private_schedule_reminders_loud_v2'));
assert(native.includes('RingtoneManager.TYPE_ALARM'));
assert(native.includes('setVibrationPattern'));
assert(native.includes('NotificationManager.IMPORTANCE_HIGH'));
assert(!native.includes('setFullScreenIntent('));
console.log('PASS office phone formats, safe tap-to-call, and strong dedicated reminder channel');
